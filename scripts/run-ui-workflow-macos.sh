#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repository_root="$(cd "$script_dir/.." && pwd)"
database="${1:?Pass an absolute runs.sqlite3 path generated by ui_workflow_fixture}"
if [[ "$database" != /* || ! -f "$database" ]]; then
    printf 'Expected an existing absolute validation database path\n' >&2
    exit 2
fi
# The app additionally verifies the fixture marker before any recovery writes.
exec /usr/bin/open -W -n \
    --env "GNSSCOPE_PREVIEW=0" \
    --env "GNSSCOPE_TEST_LIBRARY=$database" \
    --env "GNSSCOPE_THEME=${GNSSCOPE_THEME:-dark}" \
    --env "GNSSCOPE_LANGUAGE=${GNSSCOPE_LANGUAGE:-zh-CN}" \
    --env "GNSSCOPE_WINDOW_WIDTH=${GNSSCOPE_WINDOW_WIDTH:-1440}" \
    --env "GNSSCOPE_WINDOW_HEIGHT=${GNSSCOPE_WINDOW_HEIGHT:-900}" \
    "$repository_root/target/release/bundle/osx/GNSScope.app"
